package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestGeneratedTemplFilesLoseEveryCommentAndKeepTheirCode(t *testing.T) {
	dir := t.TempDir()
	src := "// Code generated by templ - DO NOT EDIT.\n\n//lint:file-ignore SA4006 reason\npackage page\n\n// doc\nfunc Value() int { return 1 /* inline */ }\n"
	if err := os.WriteFile(filepath.Join(dir, "a_templ.go"), []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "b.go"), []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	n, err := stripDir(dir)
	if err != nil || n != 1 {
		t.Fatalf("%d %v", n, err)
	}
	got, _ := os.ReadFile(filepath.Join(dir, "a_templ.go"))
	if strings.Contains(string(got), "//") || strings.Contains(string(got), "/*") || !strings.Contains(string(got), "func Value() int { return 1 }") {
		t.Fatalf("stripped:\n%s", got)
	}
	kept, _ := os.ReadFile(filepath.Join(dir, "b.go"))
	if string(kept) != src {
		t.Fatalf("a file that is not generated by templ changed:\n%s", kept)
	}
}
