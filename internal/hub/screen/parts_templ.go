func tookText(start, end string) string {
	a, errA := time.Parse(time.RFC3339Nano, start)
	b, errB := time.Parse(time.RFC3339Nano, end)
	if errA != nil || errB != nil || b.Before(a) {
		return ""
	}
	d := b.Sub(a).Round(time.Second)
	h, m, s := int(d.Hours()), int(d.Minutes())%60, int(d.Seconds())%60
	switch {
	case h > 0:
		return itoa(h) + "h " + itoa(m) + "m"
	case m > 0:
		return itoa(m) + "m " + itoa(s) + "s"
	}
	return itoa(s) + "s"
}

func tookOf(r api.RunItem) string { return tookText(r.StartedAt, r.FinishedAt) }

