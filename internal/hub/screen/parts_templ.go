type markView struct {
	tone   Tone
	glyph  string
	label  string
	hollow bool
	live   bool
}

const (
	glyphPassed  = "✓"
	glyphFailed  = "✕"
	glyphError   = "!"
	glyphSkipped = "–"
)

func markOfRun(r api.RunItem) markView {
	switch {
	case r.Mark != "":
		return markView{tone: ToneBad, glyph: glyphError, label: r.PhaseLabel}
	case r.Phase == lifecycle.Queued:
		return markView{tone: ToneIdle, label: r.PhaseLabel, hollow: true}
	case r.Phase != lifecycle.Done:
		return markView{tone: ToneWarn, label: r.PhaseLabel, live: true}
	}
	label := "no verdict"
	if r.VerdictLabel != nil {
		label = *r.VerdictLabel
	}
	switch r.Verdict {
	case lifecycle.VerdictPassed:
		return markView{tone: ToneOK, glyph: glyphPassed, label: label}
	case lifecycle.VerdictFailed:
		return markView{tone: ToneBad, glyph: glyphFailed, label: label}
	case lifecycle.VerdictError:
		return markView{tone: ToneBad, glyph: glyphError, label: label}
	case lifecycle.VerdictAborted:
		return markView{tone: ToneWarn, glyph: glyphSkipped, label: label}
	}
	return markView{tone: ToneIdle, label: label, hollow: true}
}

func markOfStatus(status string) markView {
	m := markView{tone: flowTone(status), label: statusLabel(status)}
	switch status {
	case string(contract.FlowOutcomePassed):
		m.glyph = glyphPassed
	case string(contract.FlowOutcomeFailed):
		m.glyph = glyphFailed
	case string(contract.FlowOutcomeSkipped):
		m.glyph = glyphSkipped
	case string(contract.StepStatusRunning):
		m.live = true
	default:
		m.hollow = true
	}
	return m
}

