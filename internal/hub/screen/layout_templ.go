func initials(name string) string {
	var words [][]rune
	var cur []rune
	flush := func() {
		if len(cur) > 0 {
			words = append(words, cur)
			cur = nil
		}
	}
	runes := []rune(strings.TrimSpace(name))
	for i, r := range runes {
		switch {
		case !unicode.IsLetter(r) && !unicode.IsDigit(r):
			flush()
			continue
		case i > 0 && unicode.IsUpper(r) && unicode.IsLower(runes[i-1]), i > 0 && unicode.IsDigit(r) != unicode.IsDigit(runes[i-1]):
			flush()
		}
		cur = append(cur, r)
	}
	flush()
	switch {
	case len(words) == 0:
		return "?"
	case len(words) == 1 && len(words[0]) > 1:
		return strings.ToUpper(string(words[0][:2]))
	case len(words) == 1:
		return strings.ToUpper(string(words[0]))
	}
	return strings.ToUpper(string(words[0][0]) + string(words[len(words)-1][0]))
}

func stackCount(l api.HubList) int {
	n := len(l.Foreign)
	for _, o := range l.Orphans {
		if o.Hub == "" {
			n++
		}
	}
	return n
}

func hubTitle(h api.HubItem) string {
	if h.Up {
		return h.Name + " · running at " + h.URL
	}
	return h.Name + " · not running · " + h.Home
}

func otherHubs(l api.HubList) []api.HubItem {
	var out []api.HubItem
	for _, h := range l.Hubs {
		if !h.Self {
			out = append(out, h)
		}
	}
	return out
}

func (st *state) address() string {
	if st.s == nil {
		return ""
	}
	return "127.0.0.1:" + itoa(st.s.d.Identity.Port)
}

func (st *state) onRuns() bool { return st.path != "/stacks" && st.path != "/hub" }

func sideNote(r api.RunItem) string {
	switch {
	case r.Phase == lifecycle.Queued:
		return "queued #" + itoa(r.Position)
	case isActive(r):
		return lifecycle.StageLabel(r.Phase)
	case r.Env == lifecycle.EnvUp:
		return "up"
	case r.Env == lifecycle.EnvStopped:
		return "stopped"
	}
	return r.PhaseLabel
}

